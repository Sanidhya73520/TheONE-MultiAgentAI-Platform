import PDFDocument from "pdfkit";

export const generatePdf = (data) => {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: "A4",
      margin: 50,
      info: {
        Author: "The ONE",
        Title: data.title,
        Creator: "The ONE",
      },
    });

    const chunks = [];

    doc.on("data", (chunk) => chunks.push(chunk));

    doc.on("end", () => {
      resolve(Buffer.concat(chunks));
    });

    doc.on("error", (error) => {
      reject(error);
    });

    // Title
    doc.fontSize(28).fillColor("#111827").text(data.title, {
      align: "center",
    });

    // Subtitle
    if (data.subtitle) {
      doc.moveDown(0.5).fontSize(12).fillColor("#6B7280").text(data.subtitle, {
        align: "center",
      });
    }

    doc.moveDown(2);

    // Sections
    data?.sections?.forEach((s) => {
      doc.fontSize(18).fillColor("#111827").text(s.heading);

      doc.moveDown(0.5);

      s?.points?.forEach((p) => {
        doc
          .fontSize(12)
          .fillColor("#374151")
          .text("• " + p, {
            lineGap: 5,
          });
      });

      doc.moveDown();
    });

    // Footer
    doc
      .moveDown()
      .fontSize(10)
      .fillColor("#9CA3AF")
      .text("Generated By The ONE AI", {
        align: "center",
      });

    // Finish PDF
    doc.end();
  });
};
